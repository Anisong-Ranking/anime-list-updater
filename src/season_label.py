"""公開年月から「2026夏アニメ」等の季節ラベルを作る共通ロジック。

アニメイトタイムズのTV季アニメタグページが使っている書式(冬=1-3月, 春=4-6月,
夏=7-9月, 秋=10-12月)に合わせる。台帳(auto_anime_registry.json)のキーもこの
書式なので、劇場版を検知するどちらのソース(AniList/アニメイトタイムズ映画一覧)も
ここを経由する。
"""

_SEASON_JP = {1: "冬", 2: "冬", 3: "冬", 4: "春", 5: "春", 6: "春",
              7: "夏", 8: "夏", 9: "夏", 10: "秋", 11: "秋", 12: "秋"}


def season_label_for(year: int, month: int) -> str:
    return f"{year}{_SEASON_JP[month]}アニメ"
